#!/usr/bin/env node
/**
 * Assemble src/levels.js from tools/levels.source.mjs: handcrafted tutorial
 * maps plus curated generator picks. Each level's par is computed with the
 * exact solver so it can never drift out of sync with the rules.
 *
 * Usage: node tools/build-levels.mjs
 */
import { writeFileSync } from 'node:fs';
import { parseLevel } from '../src/engine.js';
import { solve } from '../src/solver.js';
import { SOURCE } from './levels.source.mjs';

const out = [];
for (const src of SOURCE) {
  const level = parseLevel(src);
  const r = solve(level, level.blocks, 2_000_000);
  if (!r.solvable) throw new Error(`Level ${src.id} is not solvable`);
  out.push({ ...src, par: r.moves.length });
  console.log(`${String(out.length).padStart(2)} ${src.id.padEnd(16)} par ${r.moves.length}  (${r.explored} states)`);
}

const body = out
  .map((l) => {
    const fields = Object.entries(l)
      .filter(([k]) => k !== 'map')
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    return `  {\n${fields}\n    map: [\n${l.map.map((r) => `      '${r}',`).join('\n')}\n    ],\n  },`;
  })
  .join('\n');

writeFileSync(
  new URL('../src/levels.js', import.meta.url),
  `/**
 * Drift Dock levels — GENERATED by tools/build-levels.mjs from tools/levels.source.mjs.
 * Do not edit by hand. \`par\` is the optimal move count found by the solver;
 * tests/levels.test.mjs re-verifies every level and par on each run.
 *
 * Map legend — border: # wall, R/G/B/Y/P dock, ~ portal.
 *              interior: . ice, # pillar, r/g/b/y/p paint pad, R/G/B/Y/P block, S stone.
 */
export const LEVELS = [
${body}
];
`,
);
console.log(`wrote ${out.length} levels`);
